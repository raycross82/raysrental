import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { Script } from 'node:vm';
import { normalizeOrder, orderForQuote, upsertSavedQuote, encodeQuotePdf, decodeQuotePdf } from '../hq/public/assets/js/saved-quotes.js';
import { priceOrder, renderQuoteDocument } from '../hq/public/assets/js/quote-doc.js';

const store = { bookings: [{id: 7, customer: 'Existing booking', price: 123}], inventory: [], quotes: [], rev: 8, settings: {pin: 'not-exported'} };
const originalBookings = structuredClone(store.bookings);
const draft = { uid: 'test-uid', number: 'RR-1031-01', date: '2026-10-31', order: { customerName: 'José Test', phone: '2145550100', rentalDate: '2026-11-07', pickup: 'TBD', items: [{id: 'table-set', qty: 10, rate: 18}, {id: 'tablecloth', qty: 10, rate: 3}], delivery: 20, setup: 50, discount: 15, includeFreeCooler: false, includeSquareLink: true, squarePaymentUrl: 'https://square.link/u/test' } };
const first = upsertSavedQuote(store, draft, '2026-10-31T18:00:00Z');
assert.equal(first.priced.totalCents, 26500);
assert.equal(first.priced.depositCents, 5300);
assert.equal(store.quotes.length, 1);
assert.deepEqual(store.bookings, originalBookings, 'saving never creates or changes bookings');
assert.equal(first.quote.items.tables, 10);
assert.equal(first.quote.items.chairs, 60);
assert.deepEqual(orderForQuote(first.quote), normalizeOrder(draft.order));
first.quote.status = 'Signed'; first.quote.signedAt = '2026-10-31T18:01:00Z';
const second = upsertSavedQuote(store, {...draft, id:first.quote.id, order:{...draft.order, setup:75}}, '2026-10-31T18:02:00Z');
assert.equal(second.created, false); assert.equal(store.quotes.length,1);
assert.equal(second.quote.status,'Signed'); assert.equal(second.quote.signedAt,'2026-10-31T18:01:00Z');
assert.equal(second.priced.totalCents,29000); assert.equal(second.priced.depositCents,5800);
assert.equal(second.quote.number,'RR-1031-01');
assert.throws(()=>upsertSavedQuote(store,{...draft,id:999,uid:'missing'}),/removed or changed/);
const other=upsertSavedQuote(store,{...draft,uid:'different-year',date:'2027-10-31'});
assert.equal(other.created,true,'same daily number does not merge different quotes');
const pdf = new TextEncoder().encode('%PDF-1.3\n/Subject ('+encodeQuotePdf(second.quote)+')\n%%EOF');
const restored=decodeQuotePdf(pdf);
assert.equal(restored.order.customerName,'José Test');
assert.deepEqual(restored.order,orderForQuote(second.quote));
assert.ok(!new TextDecoder().decode(pdf).includes('not-exported'));
assert.equal(upsertSavedQuote(store,restored).created,false,'PDF import updates the same identity');
assert.throws(()=>decodeQuotePdf(new TextEncoder().encode('%PDF-1.4 image only')),/Older PDFs/);
assert.throws(()=>decodeQuotePdf(new TextEncoder().encode('not a PDF')),/Choose a PDF/);
const legacy={id:33, number:'Q-33',customer:'Old quote',start:'2026-11-05T09:00',end:'2026-11-07T18:00',items:{tables:4,chairs:25,coolers:2,speakers:1},delivery:20,discount:11};
const legacyOrder=orderForQuote(legacy), legacyPriced=priceOrder(legacyOrder);
assert.equal(legacyPriced.totalCents,41700); assert.equal(legacyPriced.depositCents,10400);
assert.equal(legacyOrder.bookingEnd,legacy.end); assert.equal(legacyPriced.showPromo,false);
assert.ok(renderQuoteDocument(legacyPriced,{quoteNumber:'Q-33',quoteDate:'2026-10-31'}).includes('25% Deposit to Reserve'));
const tracker=readFileSync(new URL('../hq/public/index.html',import.meta.url),'utf8');
for(const [,script] of tracker.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g)) new Script(script);
console.log('assert-saved-quotes: passed — pricing, legacy totals, preservation, identity, PDF restore, safe rejection, and tracker syntax');
